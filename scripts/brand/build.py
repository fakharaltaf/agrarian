"""Builds the AGRARIAN logo: the barn-A mark and the slab wordmark, as plain SVG path data.

Run from the repo root:  python3 scripts/brand/build.py   (needs: pip install shapely)
Writes src/app/logoArt.ts, public/favicon.svg and public/brand/*.svg. The PNGs (app icon, share
image) are rendered by scripts/brand/render.sh. Nothing here ships to players: the game
only imports the generated path strings.

The mark is a gambrel barn drawn as a letter A, on a 64-unit grid snapped to 4 units, so at 16px
every edge lands on a whole pixel. Light falls from the left, as in the game's 3D scene, so the
left faces are lighter than the right ones. The hayloft beam (the A's crossbar) and the barn door
(its counter) are real holes, so the scene behind shows through on screenshots.
"""
import os
from shapely.geometry import Polygon, box
from shapely.ops import unary_union
from glyphs import word, to_path, H

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))

# ---------------------------------------------------------------- mark geometry (y down, 64 grid)
APEX, SL, SR, FL, FR = (32, 2), (12, 22), (52, 22), (4, 62), (60, 62)
BEAM = box(0, 36, 64, 40)
DOOR = box(24, 48, 40, 64)
WINDOW = box(28, 12, 36, 20)
HOLES = unary_union([BEAM, DOOR])

outline = Polygon([APEX, SL, FL, FR, SR])
left, right = box(0, 0, 32, 64), box(32, 0, 64, 64)
roof, walls = box(0, 0, 64, 22), box(0, 22, 64, 64)
FACETS = {
    'base': outline.difference(HOLES),
    'roofL': outline.intersection(roof).intersection(left).difference(WINDOW),
    'roofR': outline.intersection(roof).intersection(right).difference(WINDOW),
    'wallL': outline.intersection(walls).intersection(left).difference(HOLES),
    'wallR': outline.intersection(walls).intersection(right).difference(HOLES),
    'window': WINDOW,
}
SOLID = outline.difference(HOLES)  # one-colour silhouette; the window is cut out too in mono
SOLID_MONO = SOLID.difference(WINDOW)

TONES = {
    'light': dict(base='#8e3a30', roofL='#9e3b2e', roofR='#7a2c23', wallL='#b24a3c', wallR='#8e3a30', window='#f4b63f', ink='#3a2e25'),
    # lifted reds so the right-hand faces still separate from a near-black background
    'dark': dict(base='#ad4638', roofL='#b8493a', roofR='#9a3a2e', wallL='#cf5b46', wallR='#ad4638', window='#f4b63f', ink='#f4ebdc'),
}


def d_of(geom):
    """Shapely polygon in y-down coords -> path d (to_path flips y, so pre-flip)."""
    from shapely import affinity
    return to_path(affinity.scale(geom, 1, -1, origin=(0, 0)), 0, -H, 1, 2)


MARK = {k: d_of(g) for k, g in FACETS.items()}
MARK_MONO = d_of(SOLID_MONO)

# ---------------------------------------------------------------- wordmark (cap height 100)
WORD_GEOM, WORD_W = word('AGRARIAN', w=21, c=9, track=13, slab=14)
WORD = to_path(WORD_GEOM, 0, 0, 1, 2)

# ---------------------------------------------------------------- lockups
# Horizontal: caps are 30/64 of the mark, centred on it, 14 units apart.
# Stacked: caps are 26 units, 12 below the mark.
H_CAP, H_GAP = 30.0, 14.0
S_CAP, S_GAP = 26.0, 12.0
HW = 64 + H_GAP + WORD_W * H_CAP / 100
SW = WORD_W * S_CAP / 100
SH = 64 + S_GAP + S_CAP


def mark_svg_body(variant):
    if variant == 'mono':
        return f'<path d="{MARK_MONO}" fill="currentColor"/>'
    t = TONES[variant]
    return ''.join(f'<path d="{MARK[k]}" fill="{t[k]}"/>' for k in ('base', 'roofL', 'roofR', 'wallL', 'wallR', 'window'))


def word_g(variant, x, y, cap):
    ink = 'currentColor' if variant == 'mono' else TONES[variant]['ink']
    return f'<path transform="translate({x:g} {y:g}) scale({cap / 100:g})" d="{WORD}" fill="{ink}"/>'


def svg(viewbox, body, label='Agrarian'):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}" role="img" aria-label="{label}"><title>{label}</title>{body}</svg>\n'


def horizontal(variant):
    return svg(f'0 0 {HW:.2f} 64', mark_svg_body(variant) + word_g(variant, 64 + H_GAP, 32 - H_CAP / 2, H_CAP))


def stacked(variant):
    mx = (SW - 64) / 2
    return svg(f'0 0 {SW:.2f} {SH:g}', f'<g transform="translate({mx:.2f} 0)">{mark_svg_body(variant)}</g>' + word_g(variant, 0, 64 + S_GAP, S_CAP))


def write(rel, text):
    p = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, 'w').write(text)
    print('wrote', rel, len(text), 'bytes')


if __name__ == '__main__':
    for v in ('light', 'dark', 'mono'):
        write(f'public/brand/agrarian-mark-{v}.svg', svg('0 0 64 64', mark_svg_body(v)))
        write(f'public/brand/agrarian-horizontal-{v}.svg', horizontal(v))
        write(f'public/brand/agrarian-stacked-{v}.svg', stacked(v))
    # Favicon: the bare mark (red reads on both light and dark browser tabs).
    write('public/favicon.svg', svg('0 0 64 64', mark_svg_body('light')))
    ts = f"""// Generated by scripts/brand/build.py — edit that script, not this file.
// The AGRARIAN mark (a gambrel barn drawn as a letter A) and the slab wordmark, as SVG path data.

/** Mark faces on a 64×64 grid, drawn in this order; `base` sits under the faces so no seam shows. Light comes from the left, like the 3D scene. */
export const MARK = {{
{chr(10).join(f"  {k}: '{v}'," for k, v in MARK.items())}
}} as const;

/** The mark as one shape (window, beam and door cut out), for single-colour use. */
export const MARK_MONO = '{MARK_MONO}';

/** "AGRARIAN" at cap height 100, starting at x = 0. */
export const WORD = '{WORD}';
export const WORD_WIDTH = {WORD_W:.2f};

export const TONES = {{
  light: {TONES['light']},
  dark: {TONES['dark']},
}} as const;

/** Lockup spacing, in mark units (the mark is 64 tall). */
export const LOCKUP = {{ hCap: {H_CAP:g}, hGap: {H_GAP:g}, sCap: {S_CAP:g}, sGap: {S_GAP:g} }} as const;
"""
    import json, re
    ts = re.sub(r"(light|dark): (\{.*\}),", lambda m: f"{m.group(1)}: {{ " + ', '.join(f"{k}: '{v}'" for k, v in TONES[m.group(1)].items()) + " },", ts)
    write('src/app/logoArt.ts', ts)
